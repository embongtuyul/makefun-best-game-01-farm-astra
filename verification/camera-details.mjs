import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { launchGame,root } from './browser.mjs';
const game=await launchGame();
const errors=[];
try {
  const page=await game.browser.newPage({viewport:{width:1280,height:720}});
  page.on('pageerror',error=>errors.push(error.message));
  const state=()=>page.evaluate(()=>window.petalpost.snapshot());
  const click=action=>page.locator(`[data-action="${action}"]`).click();
  const point=async(x,y)=> {
    const box=await page.locator('#stage').boundingBox();
    return {x:box.x+x/1280*box.width,y:box.y+y/720*box.height};
  };
  const tap=async(x,y)=> { const p=await point(x,y); await page.mouse.click(p.x,p.y); };
  await page.goto(game.url);
  await click('start');
  await click('zoom-in'); await page.waitForFunction(()=>window.petalpost.snapshot().camera.zoom>1.24);
  assert((await state()).camera.zoom>1.2);
  await page.mouse.move(640,360); await page.mouse.wheel(0,-180); await page.waitForFunction(()=>window.petalpost.snapshot().camera.zoom>1.5);
  assert((await state()).camera.zoom>1.5);
  await click('zoom-reset');
  assert.equal((await state()).camera.zoom,1);
  await click('zoom-in'); await page.waitForFunction(()=>window.petalpost.snapshot().camera.zoom>1.249);
  const ground=await point(450,600);
  await page.mouse.move(ground.x,ground.y); await page.mouse.down();
  await page.mouse.move(ground.x+300,ground.y+80,{steps:8}); await page.mouse.up();
  assert((await state()).camera.panX>0);
  assert((await state()).camera.panX<=1280*(await state()).camera.fit*((await state()).camera.targetZoom-1)/2+.1);
  assert.equal((await state()).plots[0].crop,null);
  await tap(615,305);
  assert.equal((await state()).plots[0].crop,'oat');
  await click('inspect');
  await page.waitForTimeout(300);
  await tap(615,305);
  await page.waitForFunction(()=>window.petalpost.snapshot().detail!==null);
  await page.waitForTimeout(300);
  assert.match(await page.locator('#element-detail').innerText(),/BTC.*Bitcoin/s);
  assert.match(await page.locator('#element-detail').innerText(),/Unpowered/);
  assert.equal((await state()).plots[0].watered,false);
  const before=(await state()).plots[0].progress;
  await page.waitForTimeout(700);
  assert((await state()).plots[0].progress>before);
  await click('detail-close'); await click('inspect');
  await tap(615,305);
  assert.equal((await state()).plots[0].watered,true);
  await click('zoom-reset');
  await page.goto(`${game.url}/?shot=play`);
  await page.waitForTimeout(250); await click('inspect');
  await tap(940,370); await page.locator('#element-detail h3').filter({hasText:'GPU rig'}).waitFor();
  assert.match(await page.locator('#element-detail').innerText(),/GPU rig.*Hash/s);
  await tap(527,210); await page.waitForFunction(()=>window.petalpost.snapshot().detail?.id==='hq');
  await page.locator('#element-detail h3').filter({hasText:'Exchange HQ'}).waitFor();
  assert.match(await page.locator('#element-detail').innerText(),/Exchange HQ/);
  await click('detail-shortcut');
  assert.equal((await state()).panel,'orders');
  await click('close');
  const farmer=(await state()).farmer;
  await tap(farmer.x,farmer.y-60); await page.locator('#element-detail h3').filter({hasText:'CZ'}).waitFor();
  assert.match(await page.locator('#element-detail').innerText(),/CZ/);
  await click('detail-close');
  await tap(farmer.buddyX,farmer.buddyY-25); await page.locator('#element-detail h3').filter({hasText:'BNB buddy'}).waitFor();
  assert.match(await page.locator('#element-detail').innerText(),/BNB buddy/);
  await tap(70,380); await page.waitForFunction(()=>window.petalpost.snapshot().detail===null);
  await page.locator('#element-detail').waitFor({state:'hidden'});
  assert.equal(await page.locator('#element-detail').isVisible(),false);
  // Two real touch contacts exercise the same pointer distance path as pinch.
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:100,y:380,id:1},{x:200,y:380,id:2}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:60,y:380,id:1},{x:260,y:380,id:2}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForFunction(()=>window.petalpost.snapshot().camera.zoom>1.1);
  assert((await state()).camera.zoom>1.1);
  await click('zoom-reset');
  assert.equal((await state()).camera.zoom,1);
  assert.deepEqual(errors,[]);
  const result={passed:true,errors,checks:['zoom buttons','cursor wheel','reset fit','background drag clamp','drag does not mine','tap mines after zoom/pan','live BTC detail without powering','close and normal power','GPU Hash detail','HQ shortcut','CZ and buddy details','empty ground closes','two-contact CDP pinch']};
  await writeFile(`${root}/verification/camera-result.json`,JSON.stringify(result,null,2)+'\n');
  console.log(result);
} finally { await game.close(); }
